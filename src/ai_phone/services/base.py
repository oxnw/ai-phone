"""Engine-agnostic model service protocols (architecture.md §5.1)."""
from __future__ import annotations

from typing import Iterator, Protocol

import numpy as np

Timings = dict[str, float]
Message = dict[str, str]


class STTBackend(Protocol):
    def warmup(self) -> Timings: ...
    def push(self, gen_id: int, pcm16k_f32: np.ndarray) -> str | None: ...
    def finalize(self, gen_id: int) -> tuple[str, Timings]: ...
    def cancel(self, gen_id: int) -> None: ...


class LLMBackend(Protocol):
    def warmup(self, system_prompt: str) -> Timings: ...
    def stream(self, gen_id: int, messages: list[Message], max_tokens: int) -> Iterator[str]: ...
    def cancel(self, gen_id: int) -> None: ...


class TTSBackend(Protocol):
    """TTS backends yield 20 ms PCM16 frames at their configured output rate (16 or 48 kHz)."""
    def warmup(self) -> Timings: ...
    def stream(self, gen_id: int, seq: int, text: str) -> Iterator[bytes]: ...
    def cancel(self, gen_id: int) -> None: ...
